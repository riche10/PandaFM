#!/usr/bin/env node
// Builds PandaFM's Android launcher icons from the artwork in web/assets/.
//
//   npm run android:icons              from the PNGs (1024 x 1024)
//   npm run android:icons -- --from-svg  re-export the PNGs from the SVG sources first
//
// Inputs (adaptive-icon layers, 108dp canvas; keep the important part inside
// the central 66dp circle, radius 313 px of 1024):
//   app-icon-background.png   full bleed, launchers crop it to their shape
//   app-icon-foreground.png   the panda with headphones, on transparency
//   app-icon-monochrome.png   one colour on transparency (Android 13+ themed icons)
// Output: app-icon.png (the composed full icon) and, under
// android/app/src/main/res, every mipmap Android needs: legacy square and
// round icons (API 24-25) and the adaptive layers with an adaptive-icon XML
// that includes <monochrome> (API 26+, themed on 33+).
import { access, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

let sharp
try {
  sharp = (await import('sharp')).default
} catch {
  console.error('This needs sharp: run it as `npm run android:icons` (which installs the pinned version) or `npm install --no-save sharp`.')
  process.exit(1)
}

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const assets = path.join(web, 'assets')
const res = path.join(web, 'android/app/src/main/res')
const SIZE = 1024
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 }
const fromSvg = process.argv.includes('--from-svg')

const exists = (p) => access(p).then(() => true, () => false)

async function layer(name) {
  const png = path.join(assets, `app-icon-${name}.png`)
  const svg = path.join(assets, `app-icon-${name}.svg`)
  if ((fromSvg || !(await exists(png))) && (await exists(svg))) {
    const rendered = await sharp(svg, { density: 300 }).resize(SIZE, SIZE).png().toBuffer()
    await writeFile(png, rendered) // the PNG is the artwork everything else is made from
    return rendered
  }
  if (!(await exists(png))) throw new Error(`Missing ${path.relative(web, png)} (1024 x 1024 PNG)`)
  return sharp(png).resize(SIZE, SIZE, { fit: 'cover' }).png().toBuffer()
}

const mask = (shape) => Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">${
    shape === 'round' ? `<circle cx="512" cy="512" r="512"/>` : `<rect width="${SIZE}" height="${SIZE}" rx="184"/>`
  }</svg>`,
)

const background = await layer('background')
const foreground = await layer('foreground')
const monochrome = await layer('monochrome')
const full = await sharp(background).composite([{ input: foreground }]).png().toBuffer()
await writeFile(path.join(assets, 'app-icon.png'), full)

// Legacy icons show the central 72dp of the 108dp adaptive canvas.
const inner = Math.round((SIZE * 72) / 108)
const offset = Math.round((SIZE - inner) / 2)
const legacy = await sharp(full).extract({ left: offset, top: offset, width: inner, height: inner }).resize(SIZE, SIZE).png().toBuffer()

for (const [density, scale] of Object.entries(DENSITIES)) {
  const dir = path.join(res, `mipmap-${density}`)
  await mkdir(dir, { recursive: true })
  const icon = Math.round(48 * scale)
  const adaptive = Math.round(108 * scale)
  for (const shape of ['square', 'round']) {
    const shaped = await sharp(legacy).composite([{ input: mask(shape), blend: 'dest-in' }]).png().toBuffer()
    await sharp(shaped).resize(icon, icon).png().toFile(path.join(dir, shape === 'round' ? 'ic_launcher_round.png' : 'ic_launcher.png'))
  }
  await sharp(foreground).resize(adaptive, adaptive).png().toFile(path.join(dir, 'ic_launcher_foreground.png'))
  await sharp(background).resize(adaptive, adaptive).png().toFile(path.join(dir, 'ic_launcher_background.png'))
  await sharp(monochrome).resize(adaptive, adaptive).png().toFile(path.join(dir, 'ic_launcher_monochrome.png'))
}

const adaptiveXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by web/scripts/android-icons.mjs from web/assets/app-icon-*.png -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`
await mkdir(path.join(res, 'mipmap-anydpi-v26'), { recursive: true })
for (const name of ['ic_launcher.xml', 'ic_launcher_round.xml']) await writeFile(path.join(res, 'mipmap-anydpi-v26', name), adaptiveXml)
console.log(`Android icons written for ${Object.keys(DENSITIES).join(', ')} (+ adaptive, monochrome).`)
